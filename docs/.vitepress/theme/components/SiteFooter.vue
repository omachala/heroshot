<script setup lang="ts">
import { ref, onMounted } from 'vue';

interface Article {
  title: string;
  url: string;
}

const year = new Date().getFullYear();

const fallbackArticles: Article[] = [
  {
    title: 'Screenshot from Terminal',
    url: 'https://dev.to/omachala/you-can-screenshot-any-website-from-your-terminal-2k34',
  },
  {
    title: 'Auto-Update Screenshots',
    url: 'https://dev.to/omachala/how-to-auto-update-screenshots-in-documentation-4d5c',
  },
  {
    title: 'VitePress Screenshots',
    url: 'https://dev.to/omachala/keeping-your-vitepress-screenshots-from-going-stale-477e',
  },
];

const articles = ref<Article[]>(fallbackArticles);

onMounted(async () => {
  try {
    const res = await fetch('https://dev.to/api/articles?username=omachala&per_page=3');
    if (!res.ok) return;
    const data: Array<{ title: string; url: string }> = await res.json();
    if (data.length > 0) {
      articles.value = data.map(a => ({ title: a.title, url: a.url }));
    }
  } catch {
    // Keep fallback articles
  }
});
</script>

